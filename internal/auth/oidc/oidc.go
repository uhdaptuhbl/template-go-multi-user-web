// nonceBytes is the number of random bytes a login nonce is generated from,
// matching PKCE's own recommended verifier length.
const nonceBytes = 32

// ErrUnknownProvider reports a provider key with no configuration.
var ErrUnknownProvider = errors.New("unknown provider")

// ErrInvalidState reports ceremony state that is unknown, expired, or already
// used.
var ErrInvalidState = errors.New("invalid state")

// ErrInvalidToken reports an identity token that failed validation.
var ErrInvalidToken = errors.New("invalid identity token")

// errDuplicateProviderKey reports that two configured providers share a Key,
// which would make one of them unreachable by callback and DisplayName
// ambiguous.
var errDuplicateProviderKey = errors.New("oidc: duplicate provider key")

// Claims are the fields this service reads from a validated identity token.
type Claims struct {
	Subject       string `json:"sub"`
	Issuer        string `json:"iss"`
	Email         string `json:"email"`
	EmailVerified bool   `json:"email_verified"`
	Name          string `json:"name"`
}

// tokenClaims is the wire form of Claims. It differs only in reading
// email_verified through claimBool, since some providers send that claim as
// a string.
type tokenClaims struct {
	Email         string    `json:"email"`
	EmailVerified claimBool `json:"email_verified"`
	Name          string    `json:"name"`
}

// errNotABooleanClaim reports a boolean claim sent as a string other than
// "true" or "false".
var errNotABooleanClaim = errors.New("oidc: claim is neither a boolean nor the string true or false")

// claimBool is a boolean claim that also accepts the strings "true" and
// "false", in any case. OpenID Connect Core defines email_verified as a
// JSON boolean, but some providers send it as a string; rejecting that
// would fail every login through such a provider.
type claimBool bool

// UnmarshalJSON accepts a JSON boolean or the string form of one, and
// rejects anything else.
func (value *claimBool) UnmarshalJSON(data []byte) error {
	var asBool bool
	if boolErr := json.Unmarshal(data, &asBool); boolErr == nil {
		*value = claimBool(asBool)

		return nil
	}

	var asString string
	if stringErr := json.Unmarshal(data, &asString); stringErr != nil {
		return fmt.Errorf("%w: %s", errNotABooleanClaim, data)
	}

	switch strings.ToLower(asString) {
	case "true":
		*value = true
	case "false":
		*value = false
	default:
		return fmt.Errorf("%w: %q", errNotABooleanClaim, asString)
	}

	return nil
}

// flowData is the ceremony state persisted between Start and Finish. It
// carries the PKCE verifier, the nonce, the provider the ceremony was
// started against, the digest of the browser-binding secret, and the invite
// identifier the login was bound to, if any.
type flowData struct {
	// Verifier is the PKCE code verifier generated by Start.
	Verifier string `json:"verifier"`
	// Nonce is the value sent in the authorization request and compared
	// against the identity token's nonce claim.
	Nonce string `json:"nonce"`
	// Provider is the key of the provider Start was called with. Finish
	// rejects a state presented against a different provider.
	Provider string `json:"provider"`
	// BindingDigest is the SHA-256 digest of the binding secret Start
	// returned to its caller. Only the digest is stored, never the secret
	// itself, so a later bug that returns a flow row cannot leak it.
	BindingDigest string `json:"binding_digest"`
	// InviteID is the invite this login is bound to. It is omitted, not
	// null, when Start was not given one.
	InviteID *uuid.UUID `json:"invite_id,omitempty"`
}

// providerDiscovery holds what NewProvider and its derived types return, so
// discovery runs at most once per provider.
type providerDiscovery struct {
	provider     *goidc.Provider
	oauth2Config *oauth2.Config
	verifier     *goidc.IDTokenVerifier
}

// Provider is one configured identity provider, ready to start and finish
// logins.
type Provider struct {
	key          string
	displayName  string
	issuer       string
	clientID     string
	clientSecret secret.String
	scopes       []string
	redirectURL  string
	httpClient   *http.Client
	clockSkew    time.Duration
	logger       *zap.Logger

	mu        sync.Mutex
	discovery *providerDiscovery
}

// discover returns this provider's discovery document, oauth2 configuration,
// and identity token verifier, fetching and caching them on first use.
func (p *Provider) discover(ctx context.Context) (*providerDiscovery, error) {
	p.mu.Lock()
	defer p.mu.Unlock()

	if p.discovery != nil {
		return p.discovery, nil
	}

	discoverCtx := goidc.ClientContext(ctx, p.httpClient)

	op, err := goidc.NewProvider(discoverCtx, p.issuer)
	if err != nil {
		return nil, fmt.Errorf("oidc: discovering provider %q: %w", p.key, err)
	}

	scopes := make([]string, 0, len(p.scopes)+1)
	scopes = append(scopes, goidc.ScopeOpenID)
	scopes = append(scopes, p.scopes...)

	oauth2Config := &oauth2.Config{
		ClientID:     p.clientID,
		ClientSecret: p.clientSecret.Expose(),
		Endpoint:     op.Endpoint(),
		RedirectURL:  p.redirectURL,
		Scopes:       scopes,
	}

	skew := p.clockSkew
	verifier := op.Verifier(&goidc.Config{
		ClientID: p.clientID,
		Now:      func() time.Time { return time.Now().Add(-skew) },
	})

	p.discovery = &providerDiscovery{
		provider:     op,
		oauth2Config: oauth2Config,
		verifier:     verifier,
	}

	return p.discovery, nil
}

// Registry holds every configured provider and resolves one by key.
type Registry struct {
	providers map[string]*Provider
	flows     *authflow.Store
	logger    *zap.Logger
}

// NewRegistry builds a registry from cfg. Discovery documents are fetched
// lazily on first use rather than at construction, so a provider's outage does
// not stop this process from starting.
func NewRegistry(cfg Config, flows *authflow.Store, httpClient *http.Client, logger *zap.Logger) (*Registry, error) {
	providers := make(map[string]*Provider, len(cfg.Providers))

	for _, providerCfg := range cfg.Providers {
		if _, exists := providers[providerCfg.Key]; exists {
			return nil, fmt.Errorf("%w: %q", errDuplicateProviderKey, providerCfg.Key)
		}

		providers[providerCfg.Key] = &Provider{
			key:          providerCfg.Key,
			displayName:  providerCfg.DisplayName,
			issuer:       providerCfg.Issuer,
			clientID:     providerCfg.ClientID,
			clientSecret: providerCfg.ClientSecret,
			scopes:       providerCfg.Scopes,
			redirectURL:  cfg.PublicOrigin + "/api/v1/auth/oidc/" + providerCfg.Key + "/callback",
			httpClient:   httpClient,
			clockSkew:    cfg.ClockSkew.Duration(),
			logger:       logger,
		}
	}

	return &Registry{
		providers: providers,
		flows:     flows,
		logger:    logger,
	}, nil
}

// Keys returns the configured provider keys, sorted.
func (r *Registry) Keys() []string {
	keys := make([]string, 0, len(r.providers))
	for key := range r.providers {
		keys = append(keys, key)
	}

	sort.Strings(keys)

	return keys
}

// DisplayName returns a provider's label, or an empty string when the key is
// unknown.
func (r *Registry) DisplayName(key string) string {
	provider, ok := r.providers[key]
	if !ok {
		return ""
	}

	return provider.displayName
}

// generateNonce returns 32 bytes from crypto/rand, base64url encoded.
func generateNonce() (string, error) {
	raw := make([]byte, nonceBytes)
	if _, err := rand.Read(raw); err != nil {
		return "", fmt.Errorf("oidc: generating nonce: %w", err)
	}

	return base64.RawURLEncoding.EncodeToString(raw), nil
}

// Start begins a login. It generates a PKCE verifier, a nonce, a browser
// binding secret, and a single-use state, persists them as ceremony state,
// and returns the provider URL to redirect the user agent to together with
// the raw binding secret. inviteID, when valid, is stored in that ceremony
// state so the invite is bound to this one login and travels no other way.
//
// The caller MUST set the returned binding secret as a short-lived cookie
// (__Host- prefix, Secure, HttpOnly, SameSite=Lax) and present it back to
// Finish at the callback. Only the secret's digest is persisted server-side;
// failing to round-trip the cookie reopens login CSRF, where an attacker who
// completes their own authorization step can hand the resulting callback URL
// to a victim and have the victim's browser complete a login into the
// attacker's account.
func (r *Registry) Start(ctx context.Context, key string, inviteID uuid.NullUUID) (string, string, error) {
	return r.begin(ctx, authflow.KindOIDC, key, nil, inviteID)
}

// StartLink begins a ceremony that attaches a new identity to an
// already-authenticated account rather than logging in. It persists the flow
// under authflow.KindOIDCLink with userID set, so FinishLink can recover
// which account started it without trusting whatever session cookie is
// presented back at the callback. Otherwise it behaves exactly like Start:
// same PKCE verifier, nonce, and browser-binding secret.
func (r *Registry) StartLink(ctx context.Context, key string, userID uuid.UUID) (string, string, error) {
	return r.begin(ctx, authflow.KindOIDCLink, key, &userID, uuid.NullUUID{})
}

// begin is Start and StartLink's shared body: it generates the PKCE
// verifier, nonce, and browser binding secret, persists them as ceremony
// state under kind with userID attached when non-nil, and returns the
// provider URL to redirect to together with the raw binding secret.
func (r *Registry) begin(ctx context.Context, kind authflow.Kind, key string, userID *uuid.UUID, inviteID uuid.NullUUID) (string, string, error) {
	provider, ok := r.providers[key]
	if !ok {
		return "", "", ErrUnknownProvider
	}

	disc, err := provider.discover(ctx)
	if err != nil {
		return "", "", err
	}

	verifier := oauth2.GenerateVerifier()

	nonce, err := generateNonce()
	if err != nil {
		return "", "", err
	}

	binding, err := generateNonce()
	if err != nil {
		return "", "", err
	}

	bindingDigest := sha256.Sum256([]byte(binding))

	data := flowData{
		Verifier:      verifier,
		Nonce:         nonce,
		Provider:      key,
		BindingDigest: base64.RawURLEncoding.EncodeToString(bindingDigest[:]),
	}
	if inviteID.Valid {
		id := inviteID.UUID
		data.InviteID = &id
	}

	payload, err := json.Marshal(data)
	if err != nil {
		return "", "", fmt.Errorf("oidc: encoding flow data: %w", err)
	}

	state, err := r.flows.Begin(ctx, kind, userID, payload)
	if err != nil {
		return "", "", fmt.Errorf("oidc: beginning flow: %w", err)
	}

	authURL := disc.oauth2Config.AuthCodeURL(state,
		oauth2.S256ChallengeOption(verifier),
		goidc.Nonce(nonce),
	)

	return authURL, binding, nil
}

// verifyBinding checks that a consumed flow's data was recorded for key and
// that binding hashes to the digest Start persisted for it, returning
// ErrInvalidState otherwise.
func (r *Registry) verifyBinding(data flowData, key, binding string) error {
	if data.Provider != key {
		r.logger.Warn("oidc: state issued for a different provider", zap.String("provider", key))

		return ErrInvalidState
	}

	if binding == "" {
		r.logger.Warn("oidc: finish presented no binding secret", zap.String("provider", key))

		return ErrInvalidState
	}

	presentedDigest := sha256.Sum256([]byte(binding))

	storedDigest, err := base64.RawURLEncoding.DecodeString(data.BindingDigest)
	if err != nil {
		r.logger.Warn("oidc: stored binding digest did not decode", zap.String("provider", key), zap.Error(err))

		return ErrInvalidState
	}

	if subtle.ConstantTimeCompare(presentedDigest[:], storedDigest) != 1 {
		r.logger.Warn("oidc: binding secret mismatch", zap.String("provider", key))

		return ErrInvalidState
	}

	return nil
}

// Finish completes a login. It consumes the ceremony state named by state,
// verifies that binding matches the secret Start returned and that the
// ceremony was started against key, exchanges code with the PKCE verifier,
// validates the identity token's signature, issuer, audience, and expiry,
// checks the nonce matches the one persisted, and returns the claims
// together with the invite the ceremony carried, if any.
func (r *Registry) Finish(ctx context.Context, key, state, code, binding string) (Claims, uuid.NullUUID, error) {
	claims, invite, _, err := r.finish(ctx, authflow.KindOIDC, key, state, code, binding)

	return claims, invite, err
}

// FinishLink completes an identity-link ceremony started by StartLink. It
// consumes only a authflow.KindOIDCLink flow, so a login ceremony's state
// cannot be replayed here, and returns the account identifier the flow was
// started for rather than trusting a caller-supplied one.
func (r *Registry) FinishLink(ctx context.Context, key, state, code, binding string) (Claims, uuid.UUID, error) {
	claims, _, flowUserID, err := r.finish(ctx, authflow.KindOIDCLink, key, state, code, binding)
	if err != nil {
		return Claims{}, uuid.UUID{}, err
	}

	if flowUserID == nil {
		// StartLink always sets userID on the flow it persists, so this
		// would mean a link flow reached Finish's shared body without one:
		// a defect in this package, not a caller mistake.
		return Claims{}, uuid.UUID{}, fmt.Errorf("oidc: link flow %q carried no user id", key)
	}

	return claims, *flowUserID, nil
}

// finish is Finish and FinishLink's shared body. It consumes the ceremony
// state named by state under kind, so a state issued for one kind can never
// be completed through the other, verifies that binding matches the secret
// begin returned and that the ceremony was started against key, exchanges
// code with the PKCE verifier, validates the identity token's signature,
// issuer, audience, and expiry, checks the nonce matches the one persisted,
// and returns the claims together with the invite the ceremony carried, if
// any, and the flow's stored user id, if any.
func (r *Registry) finish(ctx context.Context, kind authflow.Kind, key, state, code, binding string) (Claims, uuid.NullUUID, *uuid.UUID, error) {
	provider, ok := r.providers[key]
	if !ok {
		return Claims{}, uuid.NullUUID{}, nil, ErrUnknownProvider
	}

	flow, err := r.flows.Consume(ctx, kind, state)
	if err != nil {
		if errors.Is(err, authflow.ErrNotFound) {
			return Claims{}, uuid.NullUUID{}, nil, ErrInvalidState
		}

		return Claims{}, uuid.NullUUID{}, nil, fmt.Errorf("oidc: consuming flow: %w", err)
	}

	var data flowData
	if unmarshalErr := json.Unmarshal(flow.Data, &data); unmarshalErr != nil {
		return Claims{}, uuid.NullUUID{}, nil, fmt.Errorf("oidc: decoding flow data: %w", unmarshalErr)
	}

	err = r.verifyBinding(data, key, binding)
	if err != nil {
		return Claims{}, uuid.NullUUID{}, nil, err
	}

	disc, err := provider.discover(ctx)
	if err != nil {
		return Claims{}, uuid.NullUUID{}, nil, err
	}

	exchangeCtx := goidc.ClientContext(ctx, provider.httpClient)

	token, err := disc.oauth2Config.Exchange(exchangeCtx, code, oauth2.VerifierOption(data.Verifier))
	if err != nil {
		r.logger.Warn("oidc: token exchange failed", zap.String("provider", key), zap.Error(err))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	rawIDToken, ok := token.Extra("id_token").(string)
	if !ok {
		r.logger.Warn("oidc: token response carried no id_token", zap.String("provider", key))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	idToken, err := disc.verifier.Verify(exchangeCtx, rawIDToken)
	if err != nil {
		r.logger.Warn("oidc: identity token verification failed", zap.String("provider", key), zap.Error(err))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	if data.Nonce == "" || idToken.Nonce == "" {
		r.logger.Warn("oidc: nonce absent", zap.String("provider", key))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	if subtle.ConstantTimeCompare([]byte(idToken.Nonce), []byte(data.Nonce)) != 1 {
		r.logger.Warn("oidc: nonce mismatch", zap.String("provider", key))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	var decoded tokenClaims
	if claimsErr := idToken.Claims(&decoded); claimsErr != nil {
		r.logger.Warn("oidc: decoding identity token claims failed", zap.String("provider", key), zap.Error(claimsErr))

		return Claims{}, uuid.NullUUID{}, nil, ErrInvalidToken
	}

	claims := Claims{
		Subject:       idToken.Subject,
		Issuer:        idToken.Issuer,
		Email:         decoded.Email,
		EmailVerified: bool(decoded.EmailVerified),
		Name:          decoded.Name,
	}

	var invite uuid.NullUUID
	if data.InviteID != nil {
		invite = uuid.NullUUID{UUID: *data.InviteID, Valid: true}
	}

	return claims, invite, flow.UserID, nil
}
